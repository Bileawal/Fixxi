def translate(text: str) -> str:
    original = text
    # Keep already-English-looking strings mostly intact if few roman tokens
    low = text
    # Apply long phrases first
    items = sorted(GLOSS.items(), key=lambda kv: len(kv[0]), reverse=True)
    for src, dst in items:
        low = re.sub(r"(?i)\b" + re.escape(src) + r"\b", dst, low)

    def repl_token(m):
        w = m.group(0)
        key = w.lower()
        if key in TOKENS:
            return TOKENS[key]
        if key in GLOSS:
            return GLOSS[key]
        return w

    low = re.sub(r"[A-Za-z]+", repl_token, low)
    low = re.sub(r"\s+", " ", low)
    low = low.replace(" .", ".").replace(" ,", ",").replace(" ?", "?").replace(" !", "!")
    low = re.sub(r"\s+—\s+", " — ", low)
    low = low.strip()
    # Capitalize first letter if latin
    if low and low[0].isalpha():
        low = low[0].upper() + low[1:]
    # If translation barely changed and still has many roman markers, leave a cleaned version
    return low if low else original


def dart_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace("$", "\\$").replace("'", "\\'")


def main():
    root = json.loads(DATASET.read_text(encoding="utf-8"))
    strings = collect(root["diagnostic_engine"])
    pairs = []
    for s in strings:
        en = translate(s)
        if en != s:
            pairs.append((s, en))
        else:
            pairs.append((s, s))
    buf = []
    buf.append("// GENERATED — exact English copies of Dataset.json diagnostic strings.")
    buf.append("// ignore_for_file: lines_longer_than_80_chars")
    buf.append("const Map<String, String> kDiagnosisEn = {")
    for ru, en in pairs:
        buf.append(f"  '{dart_escape(ru)}': '{dart_escape(en)}',")
    buf.append("};")
    buf.append("")
    OUT.write_text("\n".join(buf), encoding="utf-8")
    print("wrote", OUT, "entries", len(pairs))


if __name__ == "__main__":
    main()
