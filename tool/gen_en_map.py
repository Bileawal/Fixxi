def collect(engine):
    out = set()

    def add(x):
        if isinstance(x, str) and x.strip():
            out.add(x.strip())
        elif isinstance(x, list):
            for i in x:
                add(i)

    for h in engine.get("hazards", []):
        add(h.get("label"))
        add(h.get("safety"))
    add(engine.get("hazard_default_checks"))
    for a in engine.get("appliances", []):
        add(a.get("common_checks"))
        add(a.get("common_safety"))
        for f in a.get("faults", []):
            add(f.get("label"))
            add(f.get("checks"))
            add(f.get("safety"))
            for i in f.get("issues", []):
                add(i.get("title"))
                add(i.get("cause"))
    return sorted(out)


